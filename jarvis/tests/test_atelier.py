class WorkspaceAndHttpTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        from consolidated_workbench import ConsolidatedWorkbench
        from workbench import load_config
        import threading
        self.app = ConsolidatedWorkbench(('127.0.0.1', 0), Store(Path(self.tmp.name) / 'ws'), config=load_config(None))
        threading.Thread(target=self.app.serve_forever, daemon=True).start()
        self.port = self.app.server_address[1]

    def tearDown(self):
        self.app.shutdown()
        self.app.server_close()
        self.tmp.cleanup()

    def call(self, method, path, data=None, cookie=True, origin=True):
        c = http.client.HTTPConnection('127.0.0.1', self.port, timeout=20)
        h = {'Host': '127.0.0.1:%d' % self.port}
        if cookie:
            h['Cookie'] = 'boj_session=' + self.app.token
        body = None
        if data is not None:
            body = json.dumps(data).encode()
            h['Content-Type'] = 'application/json'
            if origin:
                h['Origin'] = self.app.origin
        c.request(method, path, body, h)
        r = c.getresponse()
        raw = r.read()
        c.close()
        return r.status, (json.loads(raw) if r.getheader('Content-Type', '').startswith('application/json') else raw)

    def test_http_boundary_and_demo(self):
        self.assertEqual(self.call('GET', '/api/atelier/etat', cookie=False)[0], 401)
        self.assertEqual(self.call('POST', '/api/atelier/demo', {}, origin=False)[0], 403)
        status, demo = self.call('POST', '/api/atelier/demo', {})
        self.assertEqual(status, 200, demo)
        self.assertFalse(demo['devis']['emettable'])
        self.assertTrue(self.call('POST', '/api/atelier/demo', {})[1]['devis']['replayed'])
        status, state = self.call('GET', '/api/atelier/etat')
        self.assertEqual((state['resume']['machines'], state['resume']['machines_simulees'], state['physique']), (3, 3, False))
        self.assertTrue(all(m['observation']['lu'] for m in state['parc']['machines']))
        lines = (FIXTURES / 'prusaslicer-2.9.0-alpha1-metadonnees.gcode').read_text(encoding='utf-8').splitlines()
        status, est = self.call('POST', '/api/atelier/estimer', {'lignes': lines, 'fichier_sha256': SHA_A, 'octets': 109623})
        self.assertEqual((status, est['temps_machine_s']), (200, 1047))
        self.assertEqual(self.call('POST', '/api/atelier/estimer', {'lignes': ['G1 X10'], 'fichier_sha256': SHA_A, 'octets': 1})[0], 409)
        self.assertEqual(self.call('GET', '/atelier')[0], 200)

    def test_backup_restore_keeps_quotes_and_revokes_machine_rights(self):
        from workspace_state import restore_snapshot
        self.call('POST', '/api/atelier/demo', {})
        for cap in ('televerser', 'demarrer'):
            self.call('POST', '/api/atelier/autorisation', {'machine_id': 'SIM-FDM-1', 'capacite': cap, 'accordee_par': 'Olsen', 'motif': 'essai', 'duree_min': 60})
        self.call('POST', '/api/atelier/simulation', {'machine_id': 'SIM-FDM-1', 'panne': 'reponse_tardive', 'acceleration': 1})
