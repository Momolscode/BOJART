"""Recette de l'HTML autonome chargé en mémoire, sans connexion serveur."""
from pathlib import Path
import json, shutil
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
checks=[]
def check(name,result):
 checks.append({'name':name,'passed':bool(result)})
 if not result: raise AssertionError(name)
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path=shutil.which('chromium') or None)
 page=browser.new_page(viewport={'width':1440,'height':1050},device_scale_factor=1)
 errors=[];requests=[]
 page.on('pageerror',lambda x:errors.append(str(x)))
 page.on('request',lambda x:requests.append(x.url))
 page.set_content((ROOT/'BASE_METIER.html').read_text(),wait_until='load')
 check('54 fiches initiales',page.locator('.row').count()==54)
 check('fiche grand format initiale', 'Découper une grande sculpture' in page.locator('#detail').inner_text())
 page.get_by_role('button',name='Résine creuse',exact=True).click()
 check('recherche résine',page.locator('.row').count()>0)
 check('fiches sourcées visibles',page.locator('#detail .src').count()>0)
 check('aucune commande machine', 'Aucune valeur universelle ni autorisation' in page.locator('#detail').inner_text())
 page.locator('#query').fill('')
 page.locator('#domain').select_option('resine')
 check('filtre 8 fiches résine',page.locator('.row').count()==8)
 page.locator('#query').fill('zyxwvut987654')
 check('recherche vide sans réponse inventée','Aucune fiche trouvée' in page.locator('#detail').inner_text())
 page.locator('#query').fill('')
 page.locator('#domain').select_option('')
 page.get_by_role('button',name='Raccords',exact=True).click()
 check('raccords et tolérances','Jeux d’assemblage' in page.locator('#detail').inner_text())
 page.get_by_role('button',name='Parcours atelier',exact=True).click()
 page.locator('#procedure').select_option('P04')
 check('procédure 6 étapes',page.locator('#procedure-detail li').count()==6)
 check('procédure non exécutée','PROPOSITION · NON EXÉCUTÉE' in page.locator('#procedure-detail').inner_text())
 page.get_by_role('button',name='Données à recueillir',exact=True).click()
 check('8 registres',page.locator('#register-list .box').count()==8)
 check('inconnues null', '"model": null' in page.locator('#register-list').inner_text())
 page.get_by_role('button',name='Intégration & limites',exact=True).click()
 check('pas intégration prétendue','mais pas déployé' in page.locator('#about').inner_text())
 page.get_by_role('button',name='Fiches métier',exact=True).click()
 page.locator('#query').fill('résine creuse drainage')
 page.locator('#domain').select_option('resine')
 page.locator('.row',has_text='Évidement').click()
 check('référence exacte ouvrable',page.locator('#detail a').first.get_attribute('href').startswith('https://'))
 page.screenshot(path=str(ROOT/'preuves'/'BIBLIOTHEQUE_DESKTOP.png'),full_page=True)
 page.set_viewport_size({'width':390,'height':844})
 page.screenshot(path=str(ROOT/'preuves'/'BIBLIOTHEQUE_MOBILE.png'),full_page=True)
 check('pas débordement mobile',page.evaluate('document.documentElement.scrollWidth <= window.innerWidth+1'))
 page.emulate_media(reduced_motion='reduce')
 check('mouvement réduit',page.locator('.detail').evaluate("e=>getComputedStyle(e).animationName")== 'none')
 page.locator('#query').focus();page.keyboard.press('Tab')
 check('clavier vers filtre',page.locator('#domain').evaluate('e=>e===document.activeElement'))
 check('aucune erreur JS',not errors)
 check('aucun réseau externe automatique',not [r for r in requests if r.startswith('http')])
 browser.close()
(ROOT/'preuves'/'TESTS_INTERFACE.json').write_text(json.dumps({'method':'Chromium headless, HTML chargé via set_content ; pas de test file:// ni de serveur M03','checks':checks,'count':len(checks),'passed':all(c['passed'] for c in checks),'js_errors':errors,'network_requests':requests},ensure_ascii=False,indent=2))
print(len(checks),'contrôles interface réussis')
