def cube_stl(size=10.0, ascii=False, drop_last=False, inverted=False):
    v = [(0, 0, 0), (size, 0, 0), (size, size, 0), (0, size, 0), (0, 0, size), (size, 0, size), (size, size, size), (0, size, size)]
    faces = [(0, 2, 1), (0, 3, 2), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4), (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
    if inverted:
        faces = [(a, c, b) for a, b, c in faces]
    if drop_last:
        faces = faces[:-1]
    if ascii:
        body = ''.join('facet normal 0 0 0\nouter loop\n' + ''.join('vertex %g %g %g\n' % v[i] for i in f) + 'endloop\nendfacet\n' for f in faces)
        return ('solid cube\n' + body + 'endsolid cube\n').encode('ascii')
    out = b'\0' * 80 + struct.pack('<I', len(faces))
    for f in faces:
        out += struct.pack('<12fH', 0, 0, 0, *v[f[0]], *v[f[1]], *v[f[2]], 0)
    return out


class EstimationTests(unittest.TestCase):
    def test_slicer_duration_formats(self):
        # Formats écrits par get_time_dhms (OrcaSlicer, src/libslic3r/Utils.hpp) et PrusaSlicer.
        self.assertEqual(duration_seconds('1d 2h 3m 4s'), 93784)
        self.assertEqual(duration_seconds('17m 27s'), 1047)
        self.assertEqual(duration_seconds('12h 16m 1s'), 44161)
        self.assertEqual(duration_seconds('0.500000s'), 0.5)
        for bad in ('', '12 h', '3m 3m', 'abc', '1h -2m'):
            with self.assertRaisesRegex(Rejected, 'Durée de trancheur (illisible|ambiguë)'):
                duration_seconds(bad)

    def test_official_prusaslicer_metadata(self):
        result = slicer_estimate(FIXTURES / 'prusaslicer-2.9.0-alpha1-metadonnees.gcode')
        self.assertEqual((result['trancheur'], result['version_trancheur']), ('PrusaSlicer', '2.9.0-alpha1'))
        self.assertEqual(result['temps_machine_s'], 1047)
        self.assertEqual(result['matiere_g'], 1.76)
        self.assertEqual(result['matiere_cm3'], 1.63)
        self.assertEqual(result['matiere_declaree'], 'ABS;ABS;ABS;ABS;ABS')
        self.assertFalse(result['marque_simulation'])
        provenance = json.loads((FIXTURES / 'PROVENANCE.json').read_text(encoding='utf-8'))
        self.assertEqual(provenance['lignes'], 10)

    def test_orca_bambu_header_and_simulation_mark(self):
        # Ligne écrite pour les imprimantes Bambu par GCodeProcessor.cpp d'OrcaSlicer.
        text = ('; generated by OrcaSlicer 2.3.1 on 2026-11-01\n; model printing time: 1h 2m 3s; total estimated time: 1h 10m 3s\n'
                '; total layer number: 140\n; filament used [g] = 12.50, 3.25\n; BOJART SIMULATION - PROFIL NON VERIFIE\n')
        result = parse_slicer_metadata(text)
        self.assertEqual(result['temps_machine_s'], 4203)
        self.assertEqual(result['matiere_g'], 15.75)
        self.assertEqual(result['couches'], 140)
        self.assertTrue(result['marque_simulation'])

    def test_unknown_or_incomplete_gcode_refused(self):
        with self.assertRaisesRegex(Rejected, 'Trancheur non reconnu'):
            parse_slicer_metadata('; generated by Cura_SteamEngine 5.8\n;TIME:600\n')
        with self.assertRaisesRegex(Rejected, 'Durée estimée absente du G-code'):
            parse_slicer_metadata('; generated by PrusaSlicer 2.8.1\n; filament used [g] = 3.2\n')
        with tempfile.TemporaryDirectory() as tmp:
            p = Path(tmp) / 'binaire.bgcode'
            p.write_bytes(b'GCDE\x01\x00\x00\x00' + b'\0' * 64)
            with self.assertRaisesRegex(Rejected, 'G-code binaire'):
                slicer_estimate(p)

    def test_stl_cube_binary_ascii_and_units(self):
        g = stl_geometry(cube_stl())
        self.assertEqual((g['triangles'], g['volume_cm3'], g['boite_mm'], g['ferme']), (12, 1.0, [10.0, 10.0, 10.0], True))
        self.assertEqual(stl_geometry(cube_stl(ascii=True))['volume_cm3'], 1.0)
        inch = stl_geometry(cube_stl(size=1.0), unit='inch')
        self.assertAlmostEqual(inch['volume_cm3'], 16.387, places=3)
        self.assertTrue(stl_geometry(cube_stl(inverted=True))['orientation_inversee'])
        with self.assertRaisesRegex(Rejected, 'Unité du STL à choisir'):
            stl_geometry(cube_stl(), unit='cm')

    def test_open_mesh_has_no_volume(self):
        g = stl_geometry(cube_stl(drop_last=True))
        self.assertFalse(g['ferme'])
        self.assertIsNone(g['volume_cm3'])
        self.assertEqual(g['aretes_ouvertes'], 3)
        profile = json.loads((CONFIG / 'profil_resine.exemple.json').read_text(encoding='utf-8'))
        with self.assertRaisesRegex(Rejected, 'Maillage non fermé'):
            resin_estimate(g, profile)

    def test_resin_time_follows_layer_count(self):
        profile = json.loads((CONFIG / 'profil_resine.exemple.json').read_text(encoding='utf-8'))
        est = resin_estimate(stl_geometry(cube_stl(size=20)), profile)
        # (20 + 5 mm de supports) / 0,05 mm = 500 couches ; 5 × (30 + 6) + 495 × (2,5 + 6).
        self.assertEqual(est['couches'], 500)
        self.assertEqual(est['temps_machine_s'], 5 * 36 + 495 * 8.5)
        self.assertEqual(est['matiere_ml'], round(8.0 * 1.15, 3))
        wider = resin_estimate(stl_geometry(cube_stl(size=20)) | {'volume_cm3': 64.0}, profile)
        self.assertEqual(wider['temps_machine_s'], est['temps_machine_s'])  # même hauteur, même durée MSLA


class QuoteTests(unittest.TestCase):
    def test_example_grid_computes_but_never_issues(self):
        doc = compute(entry(), tariffs(), today=TODAY)
        self.assertIsNotNone(doc['totaux']['total_ht'])
        self.assertIsNone(doc['totaux']['total_ttc'])
        self.assertFalse(doc['emettable'])
        self.assertTrue(any('exemple' in b for b in doc['bloquants_emission']))
        self.assertTrue(any('TVA' in b for b in doc['bloquants_emission']))
        self.assertTrue(any('émetteur' in b for b in doc['bloquants_emission']))

    def test_document_adds_up_to_the_cent(self):
        doc = compute(entry(), declared(), today=TODAY)
        t = doc['totaux']
        lines = sum(Decimal(l['montant_ht']) for l in doc['lignes'])
        self.assertEqual(lines, Decimal(t['cout_revient_ht']))
        self.assertEqual(Decimal(t['cout_revient_ht']) + Decimal(t['marge_et_commission_ht']), Decimal(t['total_ht']))
        self.assertEqual(Decimal(t['total_ht']) + Decimal(t['tva']), Decimal(t['total_ttc']))
        self.assertEqual(Decimal(t['tva']), (Decimal(t['total_ht']) * Decimal('0.20')).quantize(Decimal('0.01')))
        self.assertTrue(doc['emettable'], doc['bloquants_emission'])
        self.assertEqual(doc['valide_jusqu_au'], (TODAY + timedelta(days=30)).isoformat())
        # Quantités : 2 bustes par exemplaire, finition par exemplaire, conception par lot.
        three = compute(entry(exemplaires=3), declared(), today=TODAY)
        self.assertEqual(Decimal(three['heures_main_oeuvre']), Decimal('8.50'))

    def test_same_formula_as_atelier_v11_calculate_quote(self):
        node = shutil.which('node')
        if not node:
            self.skipTest('Node.js absent : comparaison avec calculateQuote non exécutée.')
        doc = compute(entry(), declared(), today=TODAY)
        cost = Decimal(doc['totaux']['cout_revient_ht'])
        script = ("import {calculateQuote} from './sites/atelier/dist/lib/workshop.js';"
                  "console.log(JSON.stringify(calculateQuote({material:%s,hours:0,rate:0,other:0,margin:30,fee:0,quantity:1})));" % cost)
        out = subprocess.run([node, '--input-type=module', '-e', script], cwd=ROOT.parent, capture_output=True, text=True, encoding='utf-8', timeout=60)
        self.assertEqual(out.returncode, 0, out.stderr)
        js = json.loads(out.stdout)
        self.assertEqual(Decimal(str(js['price'])).quantize(Decimal('0.01')), Decimal(doc['totaux']['total_ht']))

    def test_franchise_mention(self):
        doc = compute(entry(), declared(tva={'regime': 'franchise_293B'}), today=TODAY)
        self.assertEqual(doc['totaux']['tva'], '0')
        self.assertEqual(doc['totaux']['mention_tva'], MENTION_293B)
        self.assertEqual(doc['totaux']['total_ht'], doc['totaux']['total_ttc'])

    def test_missing_values_are_never_zero(self):
        grid = declared()
        del grid['matieres']['Résine standard']
        doc = compute(entry(), grid, today=TODAY)
        self.assertIsNone(doc['totaux'])
        self.assertFalse(doc['emettable'])
        self.assertTrue(any(m['manque'] == 'tarif' for m in doc['manques']))
        no_estimate = entry()
        del no_estimate['pieces'][0]['estimation']
        self.assertIsNone(compute(no_estimate, declared(), today=TODAY)['totaux'])

    def test_fdm_requires_a_slicer(self):
        bad = entry()
        bad['pieces'][0]['estimation']['source'] = 'geometrique_resine'
        with self.assertRaisesRegex(Rejected, 'Une pièce FDM demande un tranchage'):
            compute(bad, declared(), today=TODAY)

    def test_simulation_profile_blocks_issue(self):
        e = entry()
        e['pieces'][0]['estimation']['marque_simulation'] = True
        doc = compute(e, declared(), today=TODAY)
        self.assertFalse(doc['emettable'])
        self.assertTrue(any('simulation' in b for b in doc['bloquants_emission']))

    def test_deterministic_and_strict(self):
        self.assertEqual(digest(compute(entry(), declared(), today=TODAY)), digest(compute(entry(), declared(), today=TODAY)))
        for grid, why in ((declared(marge='0.7', commission='0.3'), 'marge \\+ commission'), (declared(declare_par=''), 'qui l’a renseignée'),
                          (declared(devise='USD'), 'euro'), (declared(tva={'regime': 'franchise_293B', 'taux': '0.2'}), 'régime assujetti'),
                          (declared(validite_jours=0), 'validité')):
            with self.assertRaisesRegex(Rejected, why):
                compute(entry(), grid, today=TODAY)
        for e, why in ((entry(exemplaires=0), 'Exemplaires'), (entry(dossier_id='UNUM-1'), 'Dossier BOJ-'), (entry(inconnu=1), 'inconnu : inconnu'),
                       (entry(frais=[{'id': 'x', 'libelle': 'x', 'montant_ht': '-1'}]), 'nombre positif')):
            with self.assertRaisesRegex(Rejected, why):
                compute(e, declared(), today=TODAY)


class CommerceTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.store = Store(self.tmp.name)
        self.store.create_project('BOJ-ESSAI', 'Essai')
        self.day = [TODAY]
        self.c = Commerce(self.store, today=lambda: self.day[0])

    def tearDown(self):
        self.tmp.cleanup()

    def demande(self, rid='req-demande-1', origine='vitrine'):
        d = self.c.receive({'request_id': rid, 'dossier_id': 'BOJ-ESSAI', 'origine': origine, 'reference_source': 'INQ-1',
                            'recue_le': '2026-11-01', 'resume': 'Figurine 20 cm, PLA, peinte.'})
        self.c.transition({'request_id': rid + '-q', 'demande_id': d['demande_id'], 'revision_attendue': 1, 'etat': 'qualifiee', 'motif': 'Faisable'})
        return d['demande_id']

    def issued(self, demande_id=None, rid='q1', **kw):
        payload = {'request_id': 'essai-calc-' + rid, 'entree': entry(), 'tarifs': declared(**kw)}
        if demande_id:
            payload['demande_id'] = demande_id
        q = self.c.calculate(payload)
        i = self.c.issue({'request_id': 'essai-emit-' + rid, 'numero': q['numero'], 'version': q['version'], 'document_sha256': q['document_sha256'],
                          'destinataire': 'Client, 2 rue du Test'})
        return q, i

    def test_full_chain_and_funnel(self):
        did = self.demande()
        self.demande('req-demande-demo', origine='demonstration')
        q, i = self.issued(did)
        self.assertEqual((q['numero'], i['etat']), ('DV-2026-0001', 'emis'))
        self.c.mark_sent({'request_id': 'essai-sent-q1', 'numero': q['numero'], 'version': 1, 'document_sha256': i['document_sha256'], 'moyen': 'e-mail', 'envoye_le': '2026-11-02'})
        a = self.c.accept({'request_id': 'essai-acc-q1', 'numero': q['numero'], 'version': 1, 'document_sha256': i['document_sha256'],
                           'preuve': 'Bon pour accord signé', 'accepte_le': '2026-11-02'})
        self.assertFalse(a['production_autorisee'])
        self.assertFalse(a['external_message_sent'])
        funnel = self.c.overview()['entonnoir']
        self.assertEqual(funnel['demandes_reelles'], {'recues': 1, 'qualifiees': 1, 'devis_envoyes': 1, 'acceptees': 1, 'livrees': 0})
        self.assertEqual(funnel['demonstration'], 1)
        self.assertEqual(funnel['rapport'], {'acceptees_sur_envoyes': '1/1'})
        self.c.record_actual({'request_id': 'essai-releve-1', 'commande_id': a['commande_id'], 'piece_id': 'figurine', 'temps_machine_s': 45000,
                              'matiere': 118.0, 'source': 'simulation'})
        cmp = self.c.compare(a['commande_id'])
        self.assertEqual(cmp['pieces'][0]['sources'], ['simulation'])

    def test_receipts_are_idempotent(self):
        payload = {'request_id': 'essai-req-demande-x', 'dossier_id': 'BOJ-ESSAI', 'origine': 'email', 'reference_source': 'R', 'recue_le': '2026-11-01', 'resume': 'Socle'}
        first = self.c.receive(payload)
        again = self.c.receive(copy.deepcopy(payload))
        self.assertTrue(again['replayed'])
        self.assertEqual(first['demande_id'], again['demande_id'])
        with self.assertRaisesRegex(Rejected, 'Identifiant déjà utilisé pour une autre demande'):
            self.c.receive(dict(payload, resume='Autre chose'))
        self.assertEqual(len(self.c.overview()['demandes']), 1)

    def test_issued_quote_is_frozen(self):
        q, i = self.issued()
        with closing(sqlite3.connect(self.store.dbpath)) as db, db:
            doc = json.loads(db.execute("SELECT document_json FROM atelier_devis").fetchone()[0])
            doc['totaux']['total_ht'] = '1.00'
            db.execute('UPDATE atelier_devis SET document_json=?', (json.dumps(doc),))
        with self.assertRaisesRegex(IntegrityError, 'Devis DV-2026-0001 v1 altéré'):
            self.c.quote(q['numero'], 1)
        self.assertEqual(self.c.overview()['devis'][0]['etat'], 'altere')

    def test_acceptance_targets_one_current_version(self):
        q, i = self.issued()
        sent = {'numero': q['numero'], 'version': 1, 'document_sha256': i['document_sha256']}
        accept = dict(sent, preuve='OK', accepte_le='2026-11-02')
        with self.assertRaisesRegex(Rejected, 'Déclarer l’envoi au client avant d’enregistrer'):  # jamais envoyé
            self.c.accept(dict(accept, request_id='essai-acc-early'))
        self.c.mark_sent(dict(sent, request_id='essai-sent-1', moyen='e-mail', envoye_le='2026-11-02'))
        with self.assertRaisesRegex(Rejected, 'Cette version a changé depuis son affichage'):  # empreinte d'une autre version
            self.c.accept(dict(accept, request_id='essai-acc-wrong', document_sha256=SHA_B))
        v2 = self.c.calculate({'request_id': 'essai-calc-v2', 'entree': entry(titre='Figurine 200 mm, socle noyer'), 'tarifs': declared(), 'numero': q['numero']})
        self.assertEqual((v2['numero'], v2['version']), (q['numero'], 2))
        self.assertEqual(self.c.quote(q['numero'], 1)['etat'], 'emis')  # v1 reste valable tant que v2 n'est pas émise
        self.c.issue({'request_id': 'essai-emit-v2', 'numero': q['numero'], 'version': 2, 'document_sha256': v2['document_sha256'], 'destinataire': 'Client'})
        with self.assertRaisesRegex(Rejected, 'Cette version a été remplacée'):
            self.c.accept(dict(accept, request_id='essai-acc-old'))
        self.assertEqual(self.c.quote(q['numero'], 1)['etat'], 'remplace')

    def test_expired_quote_cannot_be_accepted(self):
        q, i = self.issued(validite_jours=10)
        self.c.mark_sent({'request_id': 'essai-sent-exp', 'numero': q['numero'], 'version': 1, 'document_sha256': i['document_sha256'], 'moyen': 'courrier', 'envoye_le': '2026-11-02'})
        self.day[0] = TODAY + timedelta(days=20)
        self.assertEqual(self.c.quote(q['numero'], 1)['etat'], 'expire')
        with self.assertRaisesRegex(Rejected, 'Devis expiré à cette date'):
            self.c.accept({'request_id': 'essai-acc-exp', 'numero': q['numero'], 'version': 1, 'document_sha256': i['document_sha256'],
                           'preuve': 'tardif', 'accepte_le': (TODAY + timedelta(days=20)).isoformat()})

    def test_example_grid_cannot_be_issued(self):
        q = self.c.calculate({'request_id': 'essai-calc-exemple', 'entree': entry(), 'tarifs': tariffs()})
        with self.assertRaisesRegex(Rejected, 'Émission impossible'):
            self.c.issue({'request_id': 'essai-emit-exemple', 'numero': q['numero'], 'version': 1, 'document_sha256': q['document_sha256'], 'destinataire': 'X'})
        grid = self.c.grid(compute(entry(), tariffs(), today=TODAY)['tarifs_sha256'])
        self.assertEqual(grid['origine'], 'exemple')

    def test_privacy_revision_and_numbering(self):
        with self.assertRaisesRegex(Rejected, 'Le résumé technique ne doit contenir ni e-mail'):
            self.c.receive({'request_id': 'essai-req-privee-1', 'dossier_id': 'BOJ-ESSAI', 'origine': 'email', 'reference_source': 'R', 'recue_le': '2026-11-01',
                            'resume': 'Rappeler au 06 12 34 56 78 ou jean@example.com'})
        with self.assertRaisesRegex(Rejected, 'Dossier inconnu'):
            self.c.receive({'request_id': 'essai-req-dossier-x', 'dossier_id': 'BOJ-INCONNU', 'origine': 'email', 'reference_source': 'R', 'recue_le': '2026-11-01', 'resume': 'x'})
        did = self.demande()
        with self.assertRaisesRegex(Rejected, 'La demande a changé depuis son affichage'):  # révision périmée
            self.c.transition({'request_id': 'essai-req-stale', 'demande_id': did, 'revision_attendue': 1, 'etat': 'abandonnee', 'motif': 'x'})
        a = self.c.calculate({'request_id': 'essai-calc-n1', 'entree': entry(), 'tarifs': declared()})
        b = self.c.calculate({'request_id': 'essai-calc-n2', 'entree': entry(), 'tarifs': declared()})
        self.assertEqual((a['numero'], b['numero']), ('DV-2026-0001', 'DV-2026-0002'))


class ParcTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.store = Store(self.tmp.name)
        self.clock = [1000.0]
        self.p = Parc(self.store, clock=lambda: self.clock[0])
        self.p.declare({'revision_attendue': 0, 'fiche': self.sheet()})
        self.n = 0

    def tearDown(self):
        self.tmp.cleanup()

    def sheet(self, **kw):
        s = {'id': 'SIM-FDM-1', 'origine': 'simulee', 'fabricant': 'Simulation', 'modele': 'FDM', 'procede': 'FDM', 'volume_utile_mm': [250, 210, 220],
             'source_volume': 'hypothèse', 'matieres': ['PLA'], 'interface': {'type': 'simulation'}}
        s.update(kw)
        return s

    def grant(self, *caps, machine='SIM-FDM-1', minutes=60):
        for cap in caps:
            self.p.grant({'machine_id': machine, 'capacite': cap, 'accordee_par': 'Olsen', 'motif': 'essai', 'duree_min': minutes})

    def order(self, cap, params=None, machine='SIM-FDM-1'):
        self.n += 1
        return self.p.order({'request_id': f'ordre-{self.n:04d}', 'machine_id': machine, 'capacite': cap, 'parametres': params or {}})

    def upload(self, sha=SHA_A, seconds=3600.0):
        return self.order('televerser', {'fichier_sha256': sha, 'nom': 'piece.gcode', 'temps_machine_s': seconds, 'marque_simulation': False})

    def start(self, sha=SHA_A, clear=True):
        return self.order('demarrer', {'fichier_sha256': sha, 'plateau_libre_confirme': clear, 'operateur': 'Olsen'})

    def count(self):
        with closing(sqlite3.connect(self.store.dbpath)) as db:
            return db.execute('SELECT COUNT(*) FROM atelier_ordres').fetchone()[0]

    def test_each_capability_needs_its_own_authorization(self):
        with self.assertRaisesRegex(Rejected, 'Aucune autorisation active « lire_etat » pour SIM-FDM-1'):
            self.order('lire_etat')
        self.grant('lire_etat')
        self.assertEqual(self.order('lire_etat')['etat'], 'confirme')
