"""Estimations de fabrication pour les devis BOJ.ART. Lecture seule, aucune machine.

Trois sources, jamais confondues :

* ``trancheur`` : métadonnées écrites par PrusaSlicer ou OrcaSlicer/Bambu Studio dans
  un G-code ASCII (formats relevés dans leur code source et un G-code officiel, voir
  ``docs/ATELIER_DEVIS_PARC.md``) ;
* ``geometrique_resine`` : modèle MSLA simple (nombre de couches × durée par couche,
  volume du maillage × supports) avec les paramètres déclarés d'une machine ;
* ``mesure`` : valeurs relevées par l'opérateur après une impression réelle.

Une estimation FDM sans trancheur est refusée : le temps dépend du parcours d'outil.
"""
from __future__ import annotations

import hashlib
import math
import re
import struct
from decimal import Decimal
from pathlib import Path

from core import Rejected

MAX_STL_BYTES = 50 * 1024 * 1024          # même plafond que le coffre de l'Atelier V11
MAX_TRIANGLES = 3_000_000
GCODE_HEAD = 256 * 1024
GCODE_TAIL = 512 * 1024

_GENERATED = re.compile(r'^; generated by (PrusaSlicer|OrcaSlicer|BambuStudio|Bambu Studio|SuperSlicer)[- ]?([0-9][\w.+-]*)?', re.M)
_TIME_PRUSA = re.compile(r'^; estimated printing time \(normal mode\) = (.+)$', re.M)
_TIME_BBL = re.compile(r'^; model printing time: ([^;]+); total estimated time: (.+)$', re.M)
_TOTAL_G = re.compile(r'^; total filament used \[g\] = ([0-9.]+)\s*$', re.M)
_LIST = {
    'filament_g': re.compile(r'^; filament used \[g\] = (.+)$', re.M),
    'filament_cm3': re.compile(r'^; filament used \[cm3\] = (.+)$', re.M),
    'filament_mm': re.compile(r'^; filament used \[mm\] = (.+)$', re.M),
}
_LAYERS = re.compile(r'^; total (?:layers count|layer number):? =? ?([0-9]+)\s*$', re.M)
_SETTING = re.compile(r'^; (filament_type|filament_density|layer_height|printer_model|nozzle_diameter) = (.+)$', re.M)
_DURATION_PART = re.compile(r'([0-9]+(?:\.[0-9]+)?)([dhms])')
SIMULATION_MARK = 'BOJART SIMULATION'


def duration_seconds(text):
    """Durée au format des trancheurs (« 1d 2h 3m 4s », « 17m 27s », « 0.500000s »)."""
    if not isinstance(text, str) or not text.strip() or len(text) > 64:
        raise Rejected('Durée de trancheur illisible.')
    clean = text.strip()
    parts = _DURATION_PART.findall(clean)
    if not parts or ''.join(v + u for v, u in parts) != clean.replace(' ', ''):
        raise Rejected('Durée de trancheur illisible : ' + clean[:40])
    units = [u for _, u in parts]
    if len(set(units)) != len(units):
        raise Rejected('Durée de trancheur ambiguë.')
    factor = {'d': 86400, 'h': 3600, 'm': 60, 's': 1}
    total = sum(float(v) * factor[u] for v, u in parts)
    if not math.isfinite(total) or total <= 0:
        raise Rejected('Durée de trancheur nulle ou invalide.')
    return round(total, 3)


def _sum_list(raw):
    values = [v.strip() for v in raw.split(',')]
    if not values or any(not re.fullmatch(r'[0-9]+(?:\.[0-9]+)?', v) for v in values):
        raise Rejected('Consommation de filament illisible.')
    return float(sum(Decimal(v) for v in values))


def read_gcode_window(path):
    """Début et fin d'un G-code ASCII : les métadonnées y sont écrites par les trancheurs."""
    path = Path(path)
    with path.open('rb') as source:
        head = source.read(GCODE_HEAD)
        if head[:8] == b'GCDE\x01\x00\x00\x00' or head[:4] == b'GCDE':
            raise Rejected('G-code binaire (.bgcode) non pris en charge : exporter un .gcode ASCII.')
        source.seek(0, 2)
        size = source.tell()
        tail = b''
        if size > GCODE_HEAD:
            source.seek(max(GCODE_HEAD, size - GCODE_TAIL))
            tail = source.read()
    digest = hashlib.sha256()
    with path.open('rb') as source:
        for block in iter(lambda: source.read(1024 * 1024), b''):
            digest.update(block)
    text = (head + b'\n' + tail).decode('utf-8', errors='replace')
    return text, digest.hexdigest(), size


def parse_slicer_metadata(text, *, sha256=None, size=None):
    """Retourne l'estimation déclarée par le trancheur. Ne lit que des commentaires."""
    if not isinstance(text, str):
        raise Rejected('Texte de G-code attendu.')
    generated = _GENERATED.search(text)
    if not generated:
        raise Rejected('Trancheur non reconnu : PrusaSlicer, OrcaSlicer ou Bambu Studio attendu.')
    slicer = generated.group(1).replace('Bambu Studio', 'BambuStudio')
    version = generated.group(2) or 'inconnue'
    bbl = _TIME_BBL.search(text)
    prusa = _TIME_PRUSA.search(text)
    if bbl:
        seconds = duration_seconds(bbl.group(2))
        time_key = 'total estimated time'
    elif prusa:
        seconds = duration_seconds(prusa.group(1))
        time_key = 'estimated printing time (normal mode)'
    else:
        raise Rejected('Durée estimée absente du G-code : exporter avec les statistiques du trancheur.')
    total = _TOTAL_G.search(text)
    grams = float(total.group(1)) if total else None
    found = {key: pattern.search(text) for key, pattern in _LIST.items()}
    if grams is None and found['filament_g']:
        grams = _sum_list(found['filament_g'].group(1))
    if grams is None or grams <= 0:
        raise Rejected('Masse de filament absente ou nulle dans le G-code.')
    settings = {m.group(1): m.group(2).strip()[:120] for m in _SETTING.finditer(text)}
    layers = _LAYERS.search(text)
    result = {
        'source': 'trancheur',
        'nature': 'estimation du trancheur, pas une durée mesurée',
        'trancheur': slicer, 'version_trancheur': version, 'cle_duree': time_key,
        'temps_machine_s': seconds,
        'matiere_g': round(grams, 3),
        'matiere_cm3': round(_sum_list(found['filament_cm3'].group(1)), 3) if found['filament_cm3'] else None,
        'filament_mm': round(_sum_list(found['filament_mm'].group(1)), 2) if found['filament_mm'] else None,
        'couches': int(layers.group(1)) if layers else None,
        'matiere_declaree': settings.get('filament_type'),
        'hauteur_couche_mm': settings.get('layer_height'),
        'modele_imprimante': settings.get('printer_model'),
        'marque_simulation': SIMULATION_MARK in text,
    }
    if sha256 is not None:
        result['fichier_sha256'] = sha256
        result['octets'] = size
    return result


def slicer_estimate(path):
    text, digest, size = read_gcode_window(path)
    return parse_slicer_metadata(text, sha256=digest, size=size)


# --- Géométrie STL --------------------------------------------------------------------

def _triangles(raw):
    if len(raw) > MAX_STL_BYTES:
        raise Rejected('STL au-delà de 50 Mio.')
    if len(raw) >= 84:
        count = struct.unpack_from('<I', raw, 80)[0]
        if 84 + 50 * count == len(raw):
            if count == 0 or count > MAX_TRIANGLES:
                raise Rejected('Nombre de triangles hors limites.')
            for row in struct.iter_unpack('<12fH', raw[84:]):
                yield row[3:6], row[6:9], row[9:12]
            return
    try:
        text = raw.decode('ascii')
    except UnicodeDecodeError as exc:
        raise Rejected('STL ni binaire cohérent ni ASCII.') from exc
    if not text.lstrip().startswith('solid'):
        raise Rejected('STL ni binaire cohérent ni ASCII.')
    vertices = re.findall(r'vertex\s+(\S+)\s+(\S+)\s+(\S+)', text)
    if not vertices or len(vertices) % 3 or len(vertices) // 3 > MAX_TRIANGLES:
        raise Rejected('STL ASCII incomplet.')
    try:
        points = [tuple(float(c) for c in v) for v in vertices]
    except ValueError as exc:
        raise Rejected('Coordonnée STL illisible.') from exc
    for i in range(0, len(points), 3):
        yield points[i], points[i + 1], points[i + 2]


def stl_geometry(raw, unit='mm'):
    """Boîte, volume signé, surface et fermeture d'un STL. Unité explicite, jamais devinée."""
    if unit not in ('mm', 'inch'):
        raise Rejected('Unité du STL à choisir : mm ou inch.')
    scale = 25.4 if unit == 'inch' else 1.0
    lo = [math.inf] * 3
    hi = [-math.inf] * 3
    volume = 0.0
    area = 0.0
    edges = {}
    count = 0
    for a, b, c in _triangles(raw):
        if not all(math.isfinite(x) for x in (*a, *b, *c)):
            raise Rejected('Coordonnée STL non finie.')
        count += 1
        for p in (a, b, c):
            for i in range(3):
                if p[i] < lo[i]:
                    lo[i] = p[i]
                if p[i] > hi[i]:
                    hi[i] = p[i]
        ux, uy, uz = b[0] - a[0], b[1] - a[1], b[2] - a[2]
        vx, vy, vz = c[0] - a[0], c[1] - a[1], c[2] - a[2]
        cx, cy, cz = uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx
        area += math.sqrt(cx * cx + cy * cy + cz * cz) / 2
        volume += (a[0] * (b[1] * c[2] - b[2] * c[1]) - a[1] * (b[0] * c[2] - b[2] * c[0])
                   + a[2] * (b[0] * c[1] - b[1] * c[0])) / 6
        keys = [tuple(round(x, 5) for x in p) for p in (a, b, c)]
        for i in range(3):
            p, q = keys[i], keys[(i + 1) % 3]
            if p == q:
                continue
            edge = (p, q) if p < q else (q, p)
            edges[edge] = edges.get(edge, 0) + 1
    if not count:
        raise Rejected('STL vide.')
    open_edges = sum(1 for n in edges.values() if n == 1)
    nonmanifold = sum(1 for n in edges.values() if n > 2)
    closed = open_edges == 0 and nonmanifold == 0
    size = [(hi[i] - lo[i]) * scale for i in range(3)]
    return {
        'triangles': count, 'unite_source': unit,
        'boite_mm': [round(v, 3) for v in size],
        'volume_cm3': round(abs(volume) * scale ** 3 / 1000, 3) if closed else None,
        'surface_cm2': round(area * scale ** 2 / 100, 3),
        'ferme': closed, 'aretes_ouvertes': open_edges, 'aretes_non_manifold': nonmanifold,
        'orientation_inversee': closed and volume < 0,
        'sha256': hashlib.sha256(raw).hexdigest(),
    }


RESIN_PROFILE_KEYS = {'hauteur_couche_mm', 'couches_base', 'exposition_base_s', 'exposition_s',
                      'cycle_couche_s', 'hauteur_supports_mm', 'part_supports', 'origine'}


def _positive(value, name, *, zero=False, maximum=None):
    if type(value) not in (int, float) or not math.isfinite(value) or value < 0 or (value == 0 and not zero):
        raise Rejected(f'{name} : nombre fini {"positif ou nul" if zero else "strictement positif"} requis.')
    if maximum is not None and value > maximum:
        raise Rejected(f'{name} hors limites.')
    return float(value)


def resin_estimate(geometry, profile):
    """Modèle MSLA : chaque couche est exposée en une fois, la durée suit la hauteur.

    temps = couches_base × (exposition_base + cycle) + couches_restantes × (exposition + cycle)
    résine = volume × (1 + part_supports). Évidement, drainage et orientation ne sont pas
    modélisés ; l'orientation est celle du STL fourni.
    """
    if not isinstance(profile, dict) or set(profile) != RESIN_PROFILE_KEYS:
        raise Rejected('Profil résine incomplet : ' + ', '.join(sorted(RESIN_PROFILE_KEYS)))
    if profile['origine'] not in ('exemple', 'declare'):
        raise Rejected('Origine du profil résine : exemple ou declare.')
    if not geometry.get('ferme') or geometry.get('volume_cm3') is None:
        raise Rejected('Maillage non fermé : volume de résine non calculable.')
    layer = _positive(profile['hauteur_couche_mm'], 'hauteur_couche_mm', maximum=0.3)
    bottom = profile['couches_base']
    if type(bottom) is not int or not 0 <= bottom <= 50:
        raise Rejected('couches_base : entier entre 0 et 50.')
    exposure_base = _positive(profile['exposition_base_s'], 'exposition_base_s', maximum=300)
    exposure = _positive(profile['exposition_s'], 'exposition_s', maximum=60)
    cycle = _positive(profile['cycle_couche_s'], 'cycle_couche_s', zero=True, maximum=120)
    lift = _positive(profile['hauteur_supports_mm'], 'hauteur_supports_mm', zero=True, maximum=50)
    support = _positive(profile['part_supports'], 'part_supports', zero=True, maximum=2)
    height = geometry['boite_mm'][2] + lift
    layers = math.ceil(round(height / layer, 6))
    first = min(bottom, layers)
    seconds = first * (exposure_base + cycle) + (layers - first) * (exposure + cycle)
    return {
        'source': 'geometrique_resine',
        'nature': 'estimation géométrique MSLA, à remplacer par le trancheur résine ou une mesure',
        'temps_machine_s': round(seconds, 1), 'couches': layers,
        'matiere_ml': round(geometry['volume_cm3'] * (1 + support), 3),
        'hauteur_imprimee_mm': round(height, 3), 'profil_origine': profile['origine'],
        'non_modelise': ['évidement et trous de drainage', 'orientation optimisée', 'temps de lavage et de post-polymérisation'],
        'fichier_sha256': geometry.get('sha256'),
    }
